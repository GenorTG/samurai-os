#!/usr/bin/env python3
"""Import Garuda's setup-wizard software list into catalog/garuda-setup-wizard.toml.

Source of truth: gitlab.com/garuda-linux/applications/toolbox,
packages/renderer/src/app/components/setup-wizard/setup-wizard.data.ts (GPL-3.0).
We copy the category/app/package lists as data (spec 08, "copy Garuda's lists") and keep them
re-syncable: run this script against a fresh checkout and diff the output.

Usage: import-garuda-catalog.py <setup-wizard.data.ts> <out.toml>
"""
from __future__ import annotations

import re
import sys
from dataclasses import dataclass, field
from pathlib import Path


@dataclass
class Item:
    id: str
    name: str
    packages: list[str] = field(default_factory=list)
    root_commands: list[str] = field(default_factory=list)
    user_commands: list[str] = field(default_factory=list)


@dataclass
class Category:
    id: str
    items: list[Item] = field(default_factory=list)


STR_LIST = re.compile(r"'((?:[^'\\]|\\.)*)'")


def parse(ts: str) -> list[Category]:
    categories: list[Category] = []
    current_cat: Category | None = None
    current_item: Item | None = None
    pending_id: str | None = None
    for raw in ts.splitlines():
        line = raw.strip()
        if m := re.match(r"id:\s*'([^']+)'", line):
            pending_id = m.group(1)
            continue
        if m := re.match(r"name:\s*'([^']+)'", line):
            name = m.group(1)
            if name.startswith("setupWizard.autoCategories."):
                current_cat = Category(id=pending_id or name.rsplit(".", 1)[-1])
                categories.append(current_cat)
                current_item = None
            elif current_cat is not None and pending_id:
                current_item = Item(id=pending_id, name=name)
                current_cat.items.append(current_item)
            pending_id = None
            continue
        if current_item is None:
            continue
        for key, attr in (("packages", "packages"), ("rootCommands", "root_commands"), ("userCommands", "user_commands")):
            if m := re.match(rf"{key}:\s*\[(.*)\]", line):
                getattr(current_item, attr).extend(STR_LIST.findall(m.group(1)))
    return categories


def toml_list(values: list[str]) -> str:
    return "[" + ", ".join('"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"' for v in values) + "]"


def render(categories: list[Category], source: str) -> str:
    out = [
        "# Generated by scripts/import-garuda-catalog.py - do not edit by hand.",
        f"# Source: {source} (Garuda Linux toolbox, GPL-3.0). Lists copied as data.",
        "# Package sources (Arch / Chaotic-AUR / [samurai]) are resolved by CI, not here.",
        "",
    ]
    for cat in categories:
        for item in cat.items:
            out.append(f"[[app]]")
            out.append(f'category = "{cat.id}"')
            out.append(f'id = "{item.id}"')
            out.append(f'name = "{item.name}"')
            out.append(f"packages = {toml_list(item.packages)}")
            if item.root_commands:
                out.append(f"root_commands = {toml_list(item.root_commands)}")
            if item.user_commands:
                out.append(f"user_commands = {toml_list(item.user_commands)}")
            out.append('origin = "garuda"')
            out.append("default = false")
            out.append("")
    return "\n".join(out)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    categories = parse(src.read_text(encoding="utf-8"))
    if not categories:
        print("no categories parsed; did the upstream format change?", file=sys.stderr)
        return 1
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(render(categories, "setup-wizard.data.ts"), encoding="utf-8")
    total = sum(len(c.items) for c in categories)
    print(f"{len(categories)} categories, {total} apps -> {dst}")
    for c in categories:
        print(f"  {c.id}: {len(c.items)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
